"""Get memory out of the store: a Cypher script (for the in-browser viewer,
which replays it into Relate's WebAssembly build), JSON, or a CLAUDE.md
section containing only memories whose receipts still check out."""

from __future__ import annotations

import json
import math
import re
from typing import Any

from .store import Store

VIEW_TRIM = 1500  # long source snapshots are trimmed in exports


def cypher_literal(v: Any) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(v) if math.isfinite(v) else "null"
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(cypher_literal(x) for x in v) + "]"
    s = str(v)
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return f"'{s}'"


def _key(k: str) -> str:
    return k if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", k) else f"`{k}`"


def _props(props: dict) -> str:
    items = []
    for k, v in props.items():
        if isinstance(v, str) and len(v) > VIEW_TRIM:
            v = v[:VIEW_TRIM] + "\n…"
        if isinstance(v, dict):
            v = json.dumps(v)
        items.append(f"{_key(k)}: {cypher_literal(v)}")
    return "{" + ", ".join(items) + "}"


def dump(store: Store) -> tuple[list[dict], list[dict]]:
    nodes = store.q("MATCH (n) WHERE NOT n:Meta RETURN elementId(n) AS id, labels(n) AS labels, properties(n) AS props")
    rels = store.q("MATCH (a)-[r]->(b) WHERE NOT a:Meta AND NOT b:Meta "
                   "RETURN elementId(a) AS s, type(r) AS t, elementId(b) AS d, properties(r) AS props")
    return nodes, rels


def to_cypher(store: Store) -> str:
    """One CREATE statement per 200 nodes, then relationships matched by a temp id."""
    nodes, rels = dump(store)
    idx = {n["id"]: i for i, n in enumerate(nodes)}
    out = ["// Receipts memory graph, exported for Relate (replay into any Relate store)."]
    for start in range(0, len(nodes), 200):
        chunk = nodes[start:start + 200]
        parts = []
        for n in chunk:
            props = dict(n["props"])
            props["_vid"] = idx[n["id"]]
            labels = "".join(f":{_key(l)}" for l in n["labels"])
            parts.append(f"({labels} {_props(props)})")
        out.append("CREATE " + ",\n  ".join(parts) + ";")
    by_type: dict[str, list[dict]] = {}
    for r in rels:
        by_type.setdefault(r["t"], []).append(r)
    for t, rows in sorted(by_type.items()):
        for start in range(0, len(rows), 300):
            data = [{"s": idx[r["s"]], "d": idx[r["d"]], "p": r["props"]} for r in rows[start:start + 300]]
            out.append(
                "UNWIND " + cypher_literal_rows(data) +
                f" AS r MATCH (a {{_vid: r.s}}), (b {{_vid: r.d}}) CREATE (a)-[x:{_key(t)}]->(b) SET x = r.p;")
    out.append("MATCH (n) REMOVE n._vid;")
    return "\n".join(out) + "\n"


def cypher_literal_rows(rows: list[dict]) -> str:
    def m(d: dict) -> str:
        items = []
        for k, v in d.items():
            if isinstance(v, dict):
                items.append(f"{_key(k)}: " + _props(v))
            else:
                items.append(f"{_key(k)}: {cypher_literal(v)}")
        return "{" + ", ".join(items) + "}"
    return "[" + ", ".join(m(r) for r in rows) + "]"


def to_json(store: Store) -> dict:
    nodes, rels = dump(store)
    return {"nodes": nodes, "relationships": rels}


def claude_md(store: Store) -> str:
    rows = store.q(
        "MATCH (f:Fact {status: 'fresh'}) "
        "OPTIONAL MATCH (f)-[c:CITES]->(e) "
        "WITH f, collect(CASE WHEN c.mode = 'quote' THEN e.path + ': \"' + c.quote + '\"' "
        "  ELSE coalesce(e.key, e.path, e.label) END) AS receipts "
        "RETURN f.id AS id, f.kind AS kind, f.text AS text, receipts ORDER BY f.kind, f.id")
    if not rows:
        return "<!-- receipts: no verified memories yet -->\n"
    titles = {"convention": "Conventions", "decision": "Decisions", "gotcha": "Gotchas", "howto": "How-tos",
              "fact": "Facts", "preference": "Preferences"}
    out = ["<!-- receipts:start (generated by `receipts export --claude-md`; every line below was verified "
           "against the code at export time) -->", "## What we know about this codebase", ""]
    for kind in ("convention", "gotcha", "decision", "fact", "howto", "preference"):
        group = [r for r in rows if r["kind"] == kind]
        if not group:
            continue
        out.append(f"### {titles[kind]}")
        for r in group:
            rec = ", ".join(f"`{x}`" for x in r["receipts"] if x)
            out.append(f"- {r['text']} ({r['id']}; receipts: {rec})")
        out.append("")
    out.append("<!-- receipts:end -->")
    return "\n".join(out) + "\n"
